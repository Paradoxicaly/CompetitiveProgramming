void solve(){
   string s; ll a,b,ab,ba; input(s,a,b,ab,ba);
   int n=sz(s);
   ll ca=count(all(s),'A'),cb=n-ca;
   ll need=max({0LL,ca-a,cb-b});
   vector<ll> ea,eb;
   ll fr=0;
   for(int i=0;i<n;){
       int j=i;
       while(j+1<n&&s[j+1]!=s[j]) j++;
       int L=j-i+1;
       if(L%2) fr+=L/2;
       else if(s[i]=='A') ea.pb(L/2);
       else eb.pb(L/2);
       i=j+1;
   }
   sort(all(ea)); sort(all(eb));
   ll got=0;
   for(ll x:ea){ if(ab>=x){ ab-=x; got+=x; } else fr+=x-1; }
   for(ll x:eb){ if(ba>=x){ ba-=x; got+=x; } else fr+=x-1; }
   got+=min(fr,ab+ba);
   print(got>=need?"YES":"NO");
}
int main(){
   ios::sync_with_stdio(false);
   cin.tie(nullptr);
   int T=1;
   if(cin>>T){
       while(T--) solve();
   }
   return 0;
}
