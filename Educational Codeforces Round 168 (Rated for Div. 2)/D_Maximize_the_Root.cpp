void solve(){
    int n;cin>>n;
    vector<ll>a(n+1),f(n+1,LLONG_MAX);
    for(int i=1;i<=n;i++)cin>>a[i];
    vi p(n+1);vector<vi>g(n+1);
    for(int i=2;i<=n;i++){cin>>p[i];g[p[i]].pb(i);}
    vi o={1};
    for(int i=0;i<sz(o);i++)for(int u:g[o[i]])o.pb(u);
    for(int i=n-1;i>0;i--){
        int v=o[i];
        if(g[v].empty())f[v]=a[v];
        else f[v]=a[v]>=f[v]?f[v]:(a[v]+f[v])/2;
        chmin(f[p[v]],f[v]);
    }
    cout<<a[1]+f[1]<<"\n";
}
